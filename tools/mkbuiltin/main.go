// Command mkbuiltin generates internal/builtin/catalog_gen.go from the
// reference Icon source tree (public domain):
//
//   - function names and arities from src/h/fdefs.h (graphics functions are
//     those inside its "#ifdef Graphics" sections);
//   - keyword names from src/h/kdefs.h;
//   - the preprocessor's predefined symbols from src/h/features.h;
//   - one-line descriptions from the documentation strings in the runtime
//     sources (src/runtime/*.r), e.g.
//     "left(s1,i,s2) - pad s1 on right with s2 to length i."
//
// Functions and keywords without such a string get descriptions from the
// fallbacks table below.
//
// Usage: go generate ./internal/builtin, or
//
//	go run ./tools/mkbuiltin [-icon dir] -o internal/builtin/catalog_gen.go
//
// The Icon tree defaults to $ICON_SRC, else ../icon from the repository
// root.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// fallbacks gives descriptions (written for icontools) for built-ins whose
// runtime source has no documentation string, mostly those generated by C
// macros.
var fallbacks = map[string]string{
	"sin":           "sin(r) - sine of r, r in radians.",
	"cos":           "cos(r) - cosine of r, r in radians.",
	"tan":           "tan(r) - tangent of r, r in radians.",
	"asin":          "asin(r) - arc sine of r, in radians.",
	"acos":          "acos(r) - arc cosine of r, in radians.",
	"exp":           "exp(r) - e raised to the power r.",
	"sqrt":          "sqrt(r) - square root of r.",
	"dtor":          "dtor(r) - convert r from degrees to radians.",
	"rtod":          "rtod(r) - convert r from radians to degrees.",
	"cset":          "cset(x) - convert x to a cset, failing if that is not possible.",
	"integer":       "integer(x) - convert x to an integer, failing if that is not possible.",
	"real":          "real(x) - convert x to a real number, failing if that is not possible.",
	"string":        "string(x) - convert x to a string, failing if that is not possible.",
	"iand":          "iand(i,j) - bitwise AND of i and j.",
	"ior":           "ior(i,j) - bitwise inclusive OR of i and j.",
	"ixor":          "ixor(i,j) - bitwise exclusive OR of i and j.",
	"get":           "get(L) - remove and produce an element from the left end of list L.",
	"pop":           "pop(L) - remove and produce an element from the left end of list L (as get).",
	"write":         "write(x1,x2,...) - write the arguments followed by a newline; a file argument directs the following output to that file.",
	"writes":        "writes(x1,x2,...) - write the arguments with no newline; a file argument directs the following output to that file.",
	"stop":          "stop(x1,x2,...) - write the arguments and a newline to &errout (or a file argument), then terminate the program with error status.",
	"WinEditRegion": "WinEditRegion(W,s,s2,x,y,w,h) - install an edit box with label s (Microsoft Windows only).",
}

var (
	fncDef  = regexp.MustCompile(`FncDef\((\w+),(\d+)\)|FncDefV\((\w+)\)`)
	kDef    = regexp.MustCompile(`KDef\((\w+),`)
	feature = regexp.MustCompile(`Feature\(\w+,\s*"(\w+)",\s*(?:"([^"]*)"|0)\)`)
	docFunc = regexp.MustCompile(`^(\w+)\s*\(([^)]*)\)\s*(\{[^}]*\})?\s*-+\s*(.*)$`)
	docKey  = regexp.MustCompile(`^&(\w+)\s*-+\s*(.*)$`)
)

type fn struct {
	name     string
	arity    int // -1: variadic
	sig      string
	doc      string
	graphics bool
}

type kw struct {
	name string
	doc  string
}

func main() {
	def := os.Getenv("ICON_SRC")
	if def == "" {
		def = defaultTree()
	}
	root := flag.String("icon", def, "reference Icon source tree")
	outFile := flag.String("o", "", "output file (default standard output)")
	flag.Parse()
	log.SetFlags(0)
	log.SetPrefix("mkbuiltin: ")

	fns := readFdefs(filepath.Join(*root, "src", "h", "fdefs.h"))
	kws := readKdefs(filepath.Join(*root, "src", "h", "kdefs.h"))
	feats := readFeatures(filepath.Join(*root, "src", "h", "features.h"))
	fdocs, kdocs := readDocs(filepath.Join(*root, "src", "runtime"))

	for _, f := range fns {
		d := fdocs[f.name]
		if d == "" {
			d = fallbacks[f.name]
		}
		if d == "" {
			log.Printf("warning: no description for %s()", f.name)
			f.sig = f.name + "()"
			continue
		}
		m := docFunc.FindStringSubmatch(d)
		if m == nil {
			log.Fatalf("cannot parse description %q", d)
		}
		f.sig = m[1] + "(" + strings.ReplaceAll(m[2], " ", "") + ")"
		f.doc = m[4]
	}
	for _, k := range kws {
		k.doc = kdocs[k.name]
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/mkbuiltin from the Icon source tree; DO NOT EDIT.\n\n")
	b.WriteString("package builtin\n\n")
	b.WriteString("var functions = []Function{\n")
	for _, f := range fns {
		fmt.Fprintf(&b, "\t{Name: %q, Arity: %d, Signature: %q, Summary: %q, Graphics: %v},\n",
			f.name, f.arity, f.sig, f.doc, f.graphics)
	}
	b.WriteString("}\n\nvar keywords = []Keyword{\n")
	for _, k := range kws {
		fmt.Fprintf(&b, "\t{Name: %q, Summary: %q},\n", k.name, k.doc)
	}
	b.WriteString("}\n\nvar predefined = []Predefined{\n")
	for _, f := range feats {
		fmt.Fprintf(&b, "\t{Name: %q, Feature: %q},\n", f[0], f[1])
	}
	b.WriteString("}\n")
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if *outFile == "" {
		os.Stdout.Write(out)
	} else if err := os.WriteFile(*outFile, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// defaultTree returns ../icon relative to the repository root, found by
// looking upwards from the current directory for go.mod.
func defaultTree() string {
	dir, err := os.Getwd()
	if err != nil {
		return "../icon"
	}
	for d := dir; ; d = filepath.Dir(d) {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return filepath.Join(filepath.Dir(d), "icon")
		}
		if filepath.Dir(d) == d {
			return "../icon"
		}
	}
}

// readFdefs returns the functions defined in fdefs.h, noting those inside
// "#ifdef Graphics" sections. Each name appears once.
func readFdefs(path string) []*fn {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var fns []*fn
	seen := map[string]bool{}
	var stack []bool // per #if: is it a Graphics section?
	inGraphics := func() bool {
		for _, g := range stack {
			if g {
				return true
			}
		}
		return false
	}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		switch {
		case strings.HasPrefix(line, "#if"):
			stack = append(stack, strings.Contains(line, "Graphics"))
			continue
		case strings.HasPrefix(line, "#else"):
			// The #else of "#ifdef Graphics" holds the non-graphics stubs.
			if len(stack) > 0 && stack[len(stack)-1] {
				stack[len(stack)-1] = false
			}
			continue
		case strings.HasPrefix(line, "#endif"):
			if len(stack) > 0 {
				stack = stack[:len(stack)-1]
			}
			continue
		}
		for _, m := range fncDef.FindAllStringSubmatch(line, -1) {
			name, arity := m[1], -1
			if name == "" {
				name = m[3]
			} else {
				fmt.Sscan(m[2], &arity)
			}
			if seen[name] {
				continue
			}
			seen[name] = true
			fns = append(fns, &fn{name: name, arity: arity, graphics: inGraphics()})
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	sort.Slice(fns, func(i, j int) bool { return fns[i].name < fns[j].name })
	return fns
}

func readKdefs(path string) []*kw {
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	var kws []*kw
	for _, m := range kDef.FindAllStringSubmatch(string(src), -1) {
		kws = append(kws, &kw{name: m[1]})
	}
	return kws
}

// readFeatures returns the symbols ipp predefines (as "1") and the
// &features string each corresponds to.
func readFeatures(path string) [][2]string {
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	var out [][2]string
	seen := map[string]bool{}
	for _, m := range feature.FindAllStringSubmatch(string(src), -1) {
		if !seen[m[1]] {
			seen[m[1]] = true
			out = append(out, [2]string{m[1], m[2]})
		}
	}
	return out
}

// readDocs collects the documentation strings of the runtime sources: runs
// of lines that begin with a string literal, concatenated.
func readDocs(dir string) (fdocs, kdocs map[string]string) {
	fdocs, kdocs = map[string]string{}, map[string]string{}
	files, err := filepath.Glob(filepath.Join(dir, "*.r"))
	if err != nil {
		log.Fatal(err)
	}
	sort.Strings(files)
	for _, file := range files {
		src, err := os.ReadFile(file)
		if err != nil {
			log.Fatal(err)
		}
		var cur []string
		flush := func() {
			if len(cur) == 0 {
				return
			}
			s := strings.Join(strings.Fields(strings.Join(cur, " ")), " ")
			cur = nil
			if m := docKey.FindStringSubmatch(s); m != nil {
				if kdocs[m[1]] == "" {
					kdocs[m[1]] = m[2]
				}
			} else if m := docFunc.FindStringSubmatch(s); m != nil {
				if fdocs[m[1]] == "" {
					fdocs[m[1]] = s
				}
			}
		}
		for line := range strings.SplitSeq(string(src), "\n") {
			t := strings.TrimSpace(line)
			if strings.HasPrefix(line, `"`) && strings.HasSuffix(t, `"`) && len(t) >= 2 {
				cur = append(cur, strings.ReplaceAll(t[1:len(t)-1], `\"`, `"`))
				continue
			}
			flush()
		}
		flush()
	}
	return fdocs, kdocs
}
